//! Chat IPC commands (daemon-backed).
//!
//! Split into focused submodules:
//! - `run`        — per-turn execution: `start_session`, `send_message`,
//!                  `cancel_turn`, `blocks_to_prompt_text`. All turns run in
//!                  the detached daemon via RPC.
//! - `attachments` - image attachments: `paste_image`, `paste_attachment`,
//!                  `paste_attachment_from_path`, shared `validate_session_id`
//!                  + `write_attachment` helpers, and a `pub(crate)`
//!                  `read_attachment` local-disk reader - NOT the Tauri
//!                  command of the same name, see `lifecycle`.
//! - `history`    — read-only transcript replays: `load_history`,
//!                  `load_history_page`, `transcript_stats`, `load_event_detail`.
//! - `daemon_bridge` - daemon `chat_event` -> `chat:<id>` event pump;
//!                  `ensure_session_attached` is its Tauri entry point.
//! - `history_list` — History-view listing pipeline: `list_history`.
//! - `lifecycle`  — AppHandle / process-tree side: `gc_attachments`,
//!                  `takeover_manual`, `detach_window`, `reattach_window`,
//!                  `respond_permission`, `respond_question`, and the
//!                  Tauri `read_attachment` command (session-aware wrapper
//!                  around `attachments::read_attachment`).
//! - `terminal`   — external-terminal spawning: `open_session_in_terminal`,
//!                  `open_terminal_in_directory`.
//!
//! All `#[tauri::command]` items are re-exported here so the parent
//! `ipc.rs` `pub use chat::*;` keeps surfacing the existing
//! `ipc::<command>` shape used by `lib.rs` `invoke_handler!`.

