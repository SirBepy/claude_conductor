// Glob re-exports so the `__cmd__<name>` symbols generated by
// `#[tauri::command]` are reachable via `crate::ipc::chat::<cmd>` (and via
// the parent `ipc.rs` `pub use chat::*;`). A named `pub use foo::bar`
// re-exports `bar` only; the macro-generated sibling stays hidden - a
// `#[tauri::command]` fn needs the glob form or `generate_handler!` can't
// find its hidden `__cmd__`/`__tauri_command_name_` sibling.
//
// `attachments::read_attachment` is `pub(crate)`, not a `#[tauri::command]`
// (kept at a frozen 1-arg signature because `daemon/methods/registry/
// attachments.rs` calls it directly by that exact path). Both globs below
// bring a `read_attachment` into this module's namespace (that plain fn,
// and `lifecycle`'s real Tauri command), which rustc treats as an
// `ambiguous_glob_imports` future-incompatibility warning rather than
// picking the command - the explicit re-export right after resolves it:
// an explicit import always wins over a glob-imported name.
